export interface ChainBatchRecord {
  batchIdHash: string;
  beekeeper: string;
  currentCustodian: string;
  harvestTimestamp: number;
  createdAt: number;
  quantityGrams: number;
  status: number;
  metadataCID: string;
  metadataHash: string;
  labReportHash: string;
  labVerified: boolean;
  recalled: boolean;
  jarCount: number;
  jarSizeGrams: number;
  packagedGrams: number;
  labVerifier: string;
}

/**
 * Read the full batch record from the blockchain.
 * Returns null if the contract is not available or batch doesn't exist.
 */
export async function getBatchFromChain(batchCode: string): Promise<ChainBatchRecord | null> {
  const c = await getContract();
  if (!c) return null;

  try {
    const batchIdHash = hashBatchCode(batchCode);
    const raw = await c.getBatch(batchIdHash);

    if (Number(raw.createdAt) === 0) return null;

    // ethers returns struct fields as array indices when ABI is not fully typed
    return {
      batchIdHash:      raw.batchIdHash as string,
      beekeeper:        raw.beekeeper as string,
      currentCustodian: raw.currentCustodian as string,
      harvestTimestamp: Number(raw.harvestTimestamp),
      createdAt:        Number(raw.createdAt),
      quantityGrams:    Number(raw.quantityGrams),
      status:           Number(raw.status),
      metadataCID:      raw.metadataCID as string,
      metadataHash:     raw.metadataHash as string,
      labReportHash:    raw.labReportHash as string,
      labVerified:      raw.labVerified as boolean,
      recalled:         raw.recalled as boolean,
      jarCount:         Number(raw.jarCount),
      jarSizeGrams:     Number(raw.jarSizeGrams),
      packagedGrams:    Number(raw.packagedGrams),
      labVerifier:      raw.labVerifier as string,
    };
  } catch (err) {
    console.error('[blockchain] getBatch error:', err);
    return null;
  }
}

/**
 * Lightweight status check — avoids fetching the full struct.
 */
export async function getBatchStatusFromChain(
  batchCode: string
): Promise<{ status: number; recalled: boolean; labVerified: boolean } | null> {
  const c = await getContract();
  if (!c) return null;

  try {
    const batchIdHash = hashBatchCode(batchCode);
    const [status, recalled, labVerified] = await c.getBatchStatus(batchIdHash) as [bigint, boolean, boolean];
    return { status: Number(status), recalled, labVerified };
  } catch (err) {
    console.error('[blockchain] getBatchStatus error:', err);
    return null;
  }
}
